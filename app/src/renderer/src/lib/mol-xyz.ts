function xyz(comment: string, atoms: [string, number, number, number][]): string {
  const body = atoms.map(([e, x, y, z]) => `${e}  ${x.toFixed(4)}  ${y.toFixed(4)}  ${z.toFixed(4)}`).join('\n')
  return `${atoms.length}\n${comment}\n${body}\n`
}

function diatomic(a: string, b: string, r: number, comment: string): string {
  return xyz(comment, [
    [a, 0, 0, r / 2],
    [b, 0, 0, -r / 2]
  ])
}

